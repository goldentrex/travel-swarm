let LIVE_RATES: Record<string, number> | null = null;

/** Install live EUR-based rates (1 EUR = rate units of `code`). Idempotent. */
export const setLiveRates = (rates: Record<string, number>): void => {
  LIVE_RATES = rates && Object.keys(rates).length > 0 ? rates : LIVE_RATES;
};

/** Units of `c` per 1 EUR — live rate when available, else the bundled table.
 *  Unknown currencies return 1 rather than throwing. */
export const rateFromEurOf = (c: Currency): number => {
  const live = LIVE_RATES?.[c];
  if (typeof live === "number" && live > 0) return live;
  return RATE_FROM_EUR[c] ?? 1;
};
